"""Run every product path once on a scratch org and dump the exact Cypher each one executed (docs/cypher.md)."""
from pathlib import Path

from core import brain as B, memory as M, messaging as Msg, presence as P
from core.db import Org, start_trace, _trace
from seed.graphhq import seed

seed("cyphdoc")
o = Org("cyphdoc")
tr = start_trace()
s = M.start_session(o, "Ishika", "Users get logged out when tokens refresh in parallel", ["mobile-app"], "Mobile 3.0")
M.recall(o, "access token expired returns 401, refresh it and retry the request", "Ishika")
P.detect_overlaps(o, s["session_id"]); P.live_sessions(o)
r = Msg.ask_org(o, "Is anyone rotating the token-service signing keys right now?", session_id=s["session_id"])
Msg.inbox(o, r["routed_to"]["id"]) if r.get("routed_to") else None
Msg.announce_change(o, "token-service", "keys rotate today", dev="Priya")
sv = M.save_solution(o, M.SaveRequest(session_id=s["session_id"], title="Refetch JWKS on unknown kid",
                                      summary="Mobile client refetches the JWKS when a token has an unknown kid.",
                                      lessons=[{"text": "Never cache the JWKS forever", "kind": "pitfall"}],
                                      builds_on=["sol_jwt_leeway"]))
M.record_reuse(o, s["session_id"], "sol_refresh_v2")
M.report_outcome(o, s["session_id"], "sol_rate_limit", worked=False, error="example failure")
h = Msg.handoff(o, s["session_id"], "half done: client patched, server pending")
M.lineage(o, "sol_idem_v4"); B.brain(o); B.who_knows(o, "kafka")
o.delete()

seen, out = set(), []
skip = ("schema.", "seed.", "org.", "t")
for e in tr:
    if e.name in seen or e.name.startswith(skip):
        continue
    seen.add(e.name)
    out.append(f"### `{e.name}`\n```cypher\n{e.cypher.strip()}\n```\n")
head = Path("docs/cypher.head.md").read_text()
Path("docs/cypher.md").write_text(head + "\n## Every query the product runs (generated by `scripts/gen_cypher_doc.py`)\n\n" + "\n".join(out))
print(len(out), "queries documented")
